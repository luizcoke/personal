"""Generate the portal catalog from the stable spreadsheet model (no monthly writes)."""
import argparse
import json
from pathlib import Path

CORE = Path(__file__).resolve().parents[1]
IDS = {'39': 'groceries', '51': 'shopping', '53': 'restaurants', '54': 'delivery',
       '64': 'travel', '66': 'other', '52': 'rides', '41': 'pharmacy',
       '27': 'maintenance', '37': 'fuel', '38': 'parking',
       'novo-openai': 'openai', 'novo-onedrive': 'onedrive', '61': 'spotify',
       '62': 'apple', '63': 'streaming', '60': 'amazon-prime',
       'novo-projetos-empresa': 'projects-business'}
# These rows describe participation, savings or receipts, not purchase purpose.
EXCLUDED = {'56', '70', 'novo-reembolso'}
LEGACY = [('snacks', 'Padaria e snacks', '54', True),
          ('leisure', 'Lazer', '64', False),
          ('transport', 'Transporte', None, False),
          ('health', 'Saúde', None, False),
          ('subscriptions', 'Assinaturas e serviços digitais', None, False),
          ('home', 'Casa', None, False)]

def catalog():
    model = json.loads((CORE / 'modelos/planilha.json').read_text(encoding='utf-8-sig'))
    rows = sorted(model['linhas'], key=lambda r: int(r.get('linha_excel') or 999))
    result = []
    for row in rows:
        line = row['linha']
        if line in EXCLUDED:
            continue
        label = row['item'].rstrip(' *')
        if line == '46': label = 'Outros — despesas básicas'
        if line == '66': label = 'Outros — estilo de vida'
        result.append(dict(id=IDS.get(line, 'sheet-' + line), label=label,
                           group=row['categoria'], food=row['categoria'] == 'Alimentação',
                           sheetLine=line, excelRow=int(row['linha_excel']), legacy=False))
    by_line = {r['sheetLine']: r for r in result}
    for id_, label, line, food in LEGACY:
        result.append(dict(id=id_, label=label + ' (anterior)', group='Categorias anteriores',
                           food=food, sheetLine=line, excelRow=by_line[line]['excelRow'] if line else None,
                           legacy=True))
    result.append(dict(id='unclassified', label='A classificar', group='Conferência', food=False,
                       sheetLine=None, excelRow=None, legacy=False))
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--site', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = catalog()
    serialized = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
    ts = '// Generated by despesas-pessoais/.core/scripts/sincronizar_categorias_portal.py.\n'
    ts += '// Names and stable sheet IDs come from .core/modelos/planilha.json.\n'
    ts += 'export const CATEGORIES = ' + serialized.rstrip() + ' as const;\n'
    ts += "export type Category = typeof CATEGORIES[number]['id'];\n"
    outputs = {CORE / 'modelos/categorias_portal.json': serialized,
               args.site / 'lib/categories.ts': ts}
    for path, value in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != value:
                raise SystemExit(f'Catálogo divergente: {path}')
        else:
            path.write_text(value, encoding='utf-8', newline='\n')
    print(f'{len(data)-len(LEGACY)-1} categorias de gastos alinhadas; {len(LEGACY)} IDs anteriores preservados.')

if __name__ == '__main__':
    main()
